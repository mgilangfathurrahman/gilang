<?php
/**
 * Create the initial store schema in PostgreSQL (Aiven).
 * Run from a trusted local shell/CLI; this is intentionally not an HTTP endpoint.
 * Example: DB_HOST=... DB_PORT=5432 DB_NAME=... DB_USER=... DB_PASSWORD=... php scripts/setup_database.php
 */

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit("Not found\n");
}

require_once __DIR__ . '/../api/config.php';

if (!db_config_ok()) {
    fwrite(STDERR, "Database configuration is incomplete. Set DB_HOST, DB_NAME, DB_USER, and DB_PASSWORD.\n");
    exit(1);
}

if (!extension_loaded('pdo_pgsql')) {
    fwrite(STDERR, "The PHP pdo_pgsql extension is required.\n");
    exit(1);
}

$username = app_env('DB_USER');
$password = app_env('DB_PASSWORD');
$dsn = db_dsn();

if ($dsn === null) {
    fwrite(STDERR, "Could not build the PostgreSQL connection string. Check DB_HOST, DB_PORT, and DB_NAME.\n");
    exit(1);
}

$statements = [
    <<<'SQL'
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(80) UNIQUE,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)
SQL,
    <<<'SQL'
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    email VARCHAR(254),
    phone VARCHAR(40),
    address TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)
SQL,
    <<<'SQL'
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(40) NOT NULL UNIQUE,
    customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'paid', 'processing', 'shipped', 'completed', 'cancelled')),
    subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    total NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)
SQL,
    <<<'SQL'
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
    product_name VARCHAR(200) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12, 2) NOT NULL CHECK (unit_price >= 0),
    line_total NUMERIC(12, 2) NOT NULL CHECK (line_total >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
)
SQL,
    'CREATE INDEX IF NOT EXISTS idx_products_active_name ON products (is_active, name)',
    'CREATE INDEX IF NOT EXISTS idx_customers_email ON customers (email)',
    'CREATE INDEX IF NOT EXISTS idx_orders_customer_id ON orders (customer_id)',
    'CREATE INDEX IF NOT EXISTS idx_orders_status_created_at ON orders (status, created_at DESC)',
    'CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON order_items (order_id)',
    'CREATE INDEX IF NOT EXISTS idx_order_items_product_id ON order_items (product_id)',
];

try {
    $pdo = new PDO($dsn, $username, $password, [
        PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        PDO::ATTR_EMULATE_PREPARES => false,
    ]);

    $pdo->beginTransaction();
    foreach ($statements as $statement) {
        $pdo->exec($statement);
    }
    $pdo->commit();

    fwrite(STDOUT, "Database schema created successfully (or already existed): products, customers, orders, order_items.\n");
} catch (Throwable $exception) {
    if (isset($pdo) && $pdo->inTransaction()) {
        $pdo->rollBack();
    }
    error_log('Database setup failed: ' . $exception->getMessage());
    fwrite(STDERR, "Database setup failed. Check your Aiven connection settings and PHP/server logs.\n");
    exit(1);
}
